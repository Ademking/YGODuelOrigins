// Writes src/data/passcodeAliases.ts: alternate-artwork passcodes (Dark Magician has six) mapped to the passcode this
// game's catalog uses, so a .ydk or ydke:// code from another simulator imports whichever artwork it lists.
// Input: assets/ocgcore/data.json.gz (npm run prepare:ocgcore). Run: npx tsx scripts/passcode-aliases.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { CARDS } from '../src/ocgcore/catalog';
import { cardImagePasscode } from '../src/data/cardImages';

const full = JSON.parse(gunzipSync(readFileSync('assets/ocgcore/data.json.gz')).toString('utf8')) as { cards: { id: string; alias: string }[] };
const ours = new Set(CARDS.map((card) => cardImagePasscode(card.id)).filter((code): code is string => !!code));
const aliases: Record<string, string> = {};
for (const row of full.cards) {
  const id = String(Number(row.id)), alias = String(Number(row.alias));
  if (alias !== '0' && !ours.has(id) && ours.has(alias)) aliases[id] = alias;
}
const entries = Object.entries(aliases).sort(([a], [b]) => Number(a) - Number(b));
writeFileSync('src/data/passcodeAliases.ts', `// Generated by scripts/passcode-aliases.ts: alternate-artwork passcode -> the passcode the catalog uses.\n`
  + `export const PASSCODE_ALIASES: Record<string, string> = {\n${entries.map(([a, b]) => `  '${a}': '${b}',`).join('\n')}\n};\n`);
console.log(`${entries.length} alternate-artwork passcodes`);
